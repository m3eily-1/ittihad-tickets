const glyph = (ch) => G[ch] || G[String(ch).toUpperCase()] || G[' '];

// columns of booleans (7 tall) for a string, one blank column between glyphs
export function bitmap(text) {
  const cols = [];
  [...text].forEach((ch, i) => {
    const g = glyph(ch);
    if (i) cols.push(new Array(7).fill(false));
    for (let x = 0; x < g[0].length; x++) cols.push(g.map((row) => row[x] === '#'));
  });
  return cols;
}

const NS = 'http://www.w3.org/2000/svg';
// An SVG dot display laid out for a fixed template (e.g. '00:00:00:00'); set() swaps characters of the
// same width and only toggles the dots that change, so CSS transitions animate each tick.
export function dotDisplay(el, template, { pitch = 10, r = 3.6 } = {}) {
  const cols = bitmap(template);
  const w = cols.length, h = 7;
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${w * pitch} ${h * pitch}`);
  svg.setAttribute('class', 'dm');
  svg.setAttribute('aria-hidden', 'true');
  const dots = [];
  for (let x = 0; x < w; x++) {
    dots[x] = [];
    for (let y = 0; y < h; y++) {
      const c = document.createElementNS(NS, 'circle');
      c.setAttribute('cx', x * pitch + pitch / 2);
      c.setAttribute('cy', y * pitch + pitch / 2);
      c.setAttribute('r', r);
      c.style.setProperty('--i', x + y);
      svg.append(c);
      dots[x][y] = c;
    }
  }
  el.append(svg);
  let cur = '';
  const set = (text) => {
    if (text === cur) return;
    cur = text;
    const b = bitmap(text);
    for (let x = 0; x < w; x++) for (let y = 0; y < h; y++) dots[x][y].classList.toggle('on', !!b[x]?.[y]);
  };
  set(template);
  return { svg, set, cols: w };
}
