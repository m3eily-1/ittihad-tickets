import puppeteer from 'puppeteer-core';
const [W = 844, H = 390, tag = 'l'] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu-rasterization', '--ignore-gpu-blocklist'] });
const page = await browser.newPage(); await page.setViewport({ width: +W, height: +H, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.evaluateOnNewDocument(() => { try { localStorage.setItem('itt-guide-seen', '1'); } catch {} });
await page.goto('http://localhost:4822/tunnel.html', { waitUntil: 'load', timeout: 90000 });
await page.waitForFunction(() => window.__tunnel && !document.querySelector('.pre'), { timeout: 60000 });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (n) => { await page.screenshot({ path: `_shots/mui/${tag}-${n}.png` }); };
await sleep(2500); await shot('1-start');
const scrollTo = async (f) => { await page.evaluate((f) => window.scrollTo(0, f * (document.documentElement.scrollHeight - innerHeight)), f); await sleep(2600); };
await scrollTo(0.12); await shot('2-door');
await page.evaluate(() => window.__tunnel.enterRoom('trophies'));
await page.waitForFunction(() => window.__tunnel.visit?.phase === 'inside', { timeout: 25000 }); await sleep(800);
// look at a trophy so the info card shows
await page.evaluate(() => { const T = window.__tunnel; }); await shot('3-room');
await page.evaluate(() => window.__tunnel.leaveRoom()); await page.waitForFunction(() => !window.__tunnel.visit, { timeout: 15000 }); await sleep(500);
await scrollTo(0.45); await shot('4-matches');
await page.evaluate(() => window.__tunnel.enterRoom('fantasy'));
await page.waitForFunction(() => window.__tunnel.visit?.phase === 'inside', { timeout: 25000 }); await sleep(900); await shot('5-fantasy');
await page.evaluate(() => document.querySelector('.js-fx-close').click()); await sleep(600); await shot('6-fantasyroom');
await page.evaluate(() => window.__tunnel.leaveRoom()); await page.waitForFunction(() => !window.__tunnel.visit, { timeout: 15000 }); await sleep(500);
await scrollTo(0.99); await sleep(1500); await shot('7-bowl');
console.log('errors', errors);
await browser.close();
